#!/usr/bin/env node
/**
 * Prepares the MiLADEiA rug for the scroll-driven weaving renderer.
 *
 * The renderer needs three things from the photograph: the artwork itself, the
 * knot gauge the rug was woven at, and where the woven inscription sits. Only
 * the artwork is a runtime asset — the knot lattice and the per-knot material
 * data are derived on the GPU at init (see weaveShaders.ts), which keeps the
 * derived data exactly in sync with the artwork and costs zero extra bytes.
 *
 *   public/rug/rug-full.webp                display artwork + no-WebGL fallback
 *   scripts/build/rug-assets/rug-meta.json  measured provenance (not shipped)
 *
 * The measured constants are mirrored in src/shared/components/rug/rugSource.ts;
 * `--check` re-measures the source and fails if either has drifted.
 *
 * Usage: node scripts/build/gen-rug-weave-assets.mjs [--check]
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE = path.join(ROOT, "scripts/build/rug-assets/miladeia-rug.webp");
const META = path.join(ROOT, "scripts/build/rug-assets/rug-meta.json");
const FULL = path.join(ROOT, "public/rug/rug-full.webp");
const CONSTANTS = path.join(ROOT, "src/shared/components/rug/rugSource.ts");

/**
 * Knot gauge, measured from the source: the individual knots forming the
 * inscription are ~2.3 source px across, i.e. ~28 knots per 10 cm — the coarse
 * tribal gauge this piece is woven at. The lattice quantises every motif, so
 * this is a measurement of the rug, not a tuning knob.
 */
const KNOT_COLUMNS = 420;

/** Display artwork width — the only runtime asset; also the no-WebGL fallback image. */
const FULL_WIDTH = 960;

/** Normalised band carrying the woven inscription, padded to the cream cartouche. */
const INSCRIPTION_BAND = { x0: 0.262, y0: 0.4995, x1: 0.732, y1: 0.5735 };

/** Luminance above which a pixel inside the band is the cream silk of a letter. */
const INSCRIPTION_THRESHOLD = 0.5;

const luma = (r, g, b) => (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;

/**
 * Counts the knots the inscription occupies. This is the regression guard: if the
 * band constants ever drift off the letters the count collapses, and the shader
 * would stop giving "MiLADEiA" its silk pile.
 */
async function measureInscription(cols, rows) {
  const { data } = await sharp(SOURCE)
    .resize({ width: cols, height: rows, kernel: "lanczos3", fit: "fill" })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const x0 = Math.round(INSCRIPTION_BAND.x0 * cols);
  const x1 = Math.round(INSCRIPTION_BAND.x1 * cols);
  const y0 = Math.round(INSCRIPTION_BAND.y0 * rows);
  const y1 = Math.round(INSCRIPTION_BAND.y1 * rows);

  let knots = 0;
  for (let y = y0; y < y1; y++) {
    for (let x = x0; x < x1; x++) {
      const i = (y * cols + x) * 3;
      if (luma(data[i], data[i + 1], data[i + 2]) > INSCRIPTION_THRESHOLD) knots++;
    }
  }
  return knots;
}

/** Reads the mirrored constants back out of the TS module so the two cannot diverge. */
async function readMirroredConstants() {
  const src = await readFile(CONSTANTS, "utf8");
  const num = (name) => {
    const m = src.match(new RegExp(`${name}:\\s*(-?[0-9.]+)`));
    return m ? Number(m[1]) : null;
  };
  return {
    knotColumns: num("knotColumns"),
    aspectRatio: num("aspectRatio"),
    band: { x0: num("x0"), y0: num("y0"), x1: num("x1"), y1: num("y1") },
  };
}

const meta = await sharp(SOURCE).metadata();
const cols = KNOT_COLUMNS;
const rows = Math.round((cols * meta.height) / meta.width);
const aspectRatio = Number((meta.width / meta.height).toFixed(6));
const inscriptionKnots = await measureInscription(cols, rows);

if (inscriptionKnots < 500) {
  console.error(
    `Inscription band captured only ${inscriptionKnots} knots — it no longer covers "MiLADEiA".`
  );
  process.exit(1);
}

const record = {
  $comment: "Generated by scripts/build/gen-rug-weave-assets.mjs — do not edit by hand.",
  source: { width: meta.width, height: meta.height },
  aspectRatio,
  knots: { columns: cols, rows },
  inscription: { text: "MiLADEiA", band: INSCRIPTION_BAND, threshold: INSCRIPTION_THRESHOLD, knots: inscriptionKnots },
  sourceSha256: createHash("sha256").update(await readFile(SOURCE)).digest("hex"),
};

if (process.argv.includes("--check")) {
  const committed = JSON.parse(await readFile(META, "utf8").catch(() => "{}"));
  const mirrored = await readMirroredConstants();
  const problems = [];

  if (committed.sourceSha256 !== record.sourceSha256) problems.push("rug-meta.json is stale (source changed)");
  if (mirrored.knotColumns !== cols) problems.push(`rugSource.ts knotColumns ${mirrored.knotColumns} != ${cols}`);
  if (mirrored.aspectRatio !== aspectRatio) problems.push(`rugSource.ts aspectRatio ${mirrored.aspectRatio} != ${aspectRatio}`);
  for (const k of ["x0", "y0", "x1", "y1"]) {
    if (mirrored.band[k] !== INSCRIPTION_BAND[k]) problems.push(`rugSource.ts inscription.${k} != ${INSCRIPTION_BAND[k]}`);
  }

  if (problems.length) {
    console.error(problems.map((p) => `  - ${p}`).join("\n"));
    console.error("run: node scripts/build/gen-rug-weave-assets.mjs");
    process.exit(1);
  }
  console.log("rug weave assets up to date");
} else {
  const full = await sharp(SOURCE)
    .resize({ width: FULL_WIDTH, kernel: "lanczos3", withoutEnlargement: true })
    .webp({ quality: 78, effort: 6 })
    .toBuffer();
  await writeFile(FULL, full);
  await writeFile(META, `${JSON.stringify(record, null, 2)}\n`);

  console.log(
    `rug-full.webp ${(full.length / 1024).toFixed(0)}kb  ` +
      `lattice ${cols}x${rows} knots  aspect ${aspectRatio}  ` +
      `inscription ${inscriptionKnots} knots`
  );
}
